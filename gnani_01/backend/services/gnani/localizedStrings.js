/** Returns dialogue and UI strings for any registry language. */
function getStrings(lang) {
  if (S[lang]) return Object.assign({ stringsLang: lang, isFallback: false }, S[lang]);
  const fb = TEXT_FALLBACK[lang] || 'en-IN';
  return Object.assign({ stringsLang: fb, isFallback: true }, S[fb] || S['en-IN']);
}

function getUIStrings(lang) {
  const data = getStrings(lang);
  return data.ui || S['en-IN'].ui;
}

const hasNativeStrings = (lang) => Boolean(S[lang]);

module.exports = {
  getStrings,
  getUIStrings,
  hasNativeStrings,
  STRINGS: S
};
